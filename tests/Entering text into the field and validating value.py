# Импорт основного модуля Selenium для управления браузером
from selenium import webdriver

# Импорт класс By — он содержит все стратегии поиска элементов (ID, NAME, CSS, XPATH и т.д.)
from selenium.webdriver.common.by import By

# Создание экземпляря драйвера для браузера Chrome.
# P.S. Предварительно должен быть установлен ChromeDriver и добавлен в PATH,
# либо указан путь к нему.
driver = webdriver.Chrome()

# Открытие страницы с тестовым полем ввода на сайте the-internet.herokuapp.com
driver.get("https://the-internet.herokuapp.com/inputs")

# Использование блока try/finally, чтобы гарантировать закрытие браузера даже при ошибке
try:
    # Нахождение первого (и единственного) элемента <input> на странице по имени тега.
    # By.TAG_NAME — локатор, который ищет элементы по HTML-тегу.
    input_element = driver.find_element(By.TAG_NAME, "input")
    
    # Метод send_keys() имитирует ввод текста с клавиатуры.
    # Передача строки "Привет, автотест!"
    input_element.send_keys("Привет, автотест!")
    
    # get_attribute("value") получает текущее значение, которое находится в поле ввода.
    # Это то, что реально видит пользователь и что отправляется на сервер.
    entered_text = input_element.get_attribute("value")
    
    # assert — проверка условия. Если условие ложно, программа выбросит исключение и тест упадёт. 
    # Сравниваем введённый текст с ожидаемым.
    # Если не совпадает — выводим понятное сообщение об ошибке (f-строка).
    assert entered_text == "Привет, автотест!", f"Ожидалось 'Привет, автотест!', получено '{entered_text}'"
    
    # clear() очищает поле ввода (удаляет весь текст).
    input_element.clear()
    
    # Ввод числа "12345"
    input_element.send_keys("12345")
    
    # Снова проверка значения в поле. Должно быть "12345"
    assert input_element.get_attribute("value") == "12345"
    
    # Если все проверки прошли, печать сообщения об успехе в консоль.
    print("✅ Ввод работает корректно")

# Блок finally выполняется в любом случае — даже если внутри try произошла ошибка.
finally:
    # driver.quit() закрывает все окна браузера и завершает сессию WebDriver.
    driver.quit()
